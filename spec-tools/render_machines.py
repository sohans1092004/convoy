"""Render docs/rules/state-machines/README.md (Mermaid + tables) from the machine YAML files.

python spec-tools/render_machines.py          # write README.md
python spec-tools/render_machines.py --check  # exit 1 if README.md is stale
"""
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).parent))
import miniyaml

ROOT = pathlib.Path(__file__).resolve().parent.parent
SM_DIR = ROOT / 'docs' / 'rules' / 'state-machines'
ORDER = ['pool', 'membership', 'round', 'quote', 'order', 'booking', 'payment', 'refund', 'dispute']
NONE = '(none)'


def as_list(v):
    return v if isinstance(v, list) else [v]


def load_machines():
    return {name: miniyaml.load(SM_DIR / f'{name}.yaml') for name in ORDER}


def edges(m):
    """(from, to, transition) for every concrete edge; from may be '(none)'."""
    return [(f, t['to'], t) for t in m['transitions'] for f in as_list(t['from'])]


def invalid_pairs(m):
    """Every (from, to) state pair with no transition: the exhaustive invalid set (409 invalid-transition)."""
    states = [s['name'] for s in m['states']]
    valid = {(f, to) for f, to, _ in edges(m)}
    return [(f, to) for f in states for to in states if (f, to) not in valid]


def render(machines):
    out = ['# State machines', '',
           'Generated by `spec-tools/render_machines.py` from the YAML files in this folder. **Do not edit by hand**; edit the YAML and re-run.',
           'The YAML files are the contract: later phases load them as test tables (`spec-tools/vectors/transitions.json` is derived from them).', '',
           'Conventions: `(none)` = creation. `crash_points` / `idempotent_repeat` values in CAPS refer to [`_patterns.yaml`](_patterns.yaml).',
           'Every (from, to) pair not listed is invalid and returns `409` with problem type `invalid-transition`; specific commands map to more precise problem types (see each machine\'s *Invalid commands* table and [`../../architecture/problem-types.yaml`](../../architecture/problem-types.yaml)).', '']
    for name in ORDER:
        m = machines[name]
        terminals = [s['name'] for s in m['states'] if s['terminal']]
        out += [f'## {name}', '',
                f'Owner service: **{m["owner"]}** · aggregate `{m["aggregate"]}` · source [`{name}.yaml`]({name}.yaml) · {m.get("plan_ref", "")}', '']
        if m.get('notes'):
            out += [m['notes'], '']
        out += ['```mermaid', 'stateDiagram-v2']
        out.append(f'    [*] --> {m["initial"]}')
        for f, to, t in edges(m):
            src = '[*]' if f == NONE else f
            if src == '[*]' and to == m['initial']:
                continue
            label = f'{t["id"]} {t["trigger"]["kind"]}'
            out.append(f'    {src} --> {to} : {label}')
        for s in terminals:
            out.append(f'    {s} --> [*]')
        out += ['```', '', f'Terminal states: {", ".join(f"`{s}`" for s in terminals)}', '',
                '| ID | From | To | Trigger | Guard | Emits |', '|---|---|---|---|---|---|']
        for t in m['transitions']:
            tr = t['trigger']
            out.append(f'| {t["id"]} | {", ".join(as_list(t["from"]))} | {t["to"]} | {tr["kind"]}: {tr["by"]} | {t["guard"].replace("|", "/")} | {", ".join(t["emits"]) or "-"} |')
        out += ['', '**Invalid commands**', '', '| From | Attempt | Problem type |', '|---|---|---|']
        for inv in m['invalid_transitions']:
            out.append(f'| {", ".join(as_list(inv["from"]))} | {inv["attempt"]} | `{inv["error"]}` |')
        pairs = invalid_pairs(m)
        out += ['', f'<details><summary>All {len(pairs)} invalid (from → to) state pairs → 409 invalid-transition</summary>', '']
        by_from = {}
        for f, to in pairs:
            by_from.setdefault(f, []).append(to)
        for f, tos in by_from.items():
            out.append(f'- `{f}` ↛ {", ".join(tos)}')
        out += ['', '</details>', '']
    return '\n'.join(out) + '\n'


if __name__ == '__main__':
    text = render(load_machines())
    target = SM_DIR / 'README.md'
    if '--check' in sys.argv:
        ok = target.exists() and target.read_text(encoding='utf-8') == text
        print('README.md', 'up to date' if ok else 'STALE: run spec-tools/render_machines.py')
        sys.exit(0 if ok else 1)
    target.write_text(text, encoding='utf-8', newline='\n')
    print('wrote', target.relative_to(ROOT))
