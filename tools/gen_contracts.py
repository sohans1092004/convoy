"""Generate event payload types from docs/architecture/events/*.schema.json (stdlib only).

python tools/gen_contracts.py          # write Java records + TypeScript types
python tools/gen_contracts.py --check  # exit 1 if generated files are stale (CI)

Java:  libs/contracts/src/main/java/convoy/contracts/events/<Event>.java  (records, snake_case JSON names)
TS:    packages/contracts/src/events.ts
"""
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SCHEMAS = ROOT / 'docs' / 'architecture' / 'events'
JAVA_DIR = ROOT / 'libs' / 'contracts' / 'src' / 'main' / 'java' / 'convoy' / 'contracts' / 'events'
TS_FILE = ROOT / 'packages' / 'contracts' / 'src' / 'events.ts'
CATALOGUE = ROOT / 'docs' / 'architecture' / 'event-catalogue.yaml'
sys.path.insert(0, str(ROOT / 'spec-tools'))
import miniyaml  # noqa: E402
HEADER = 'Generated by tools/gen_contracts.py from docs/architecture/events. Do not edit.'


def camel(s):
    head, *rest = s.split('_')
    return head + ''.join(p[:1].upper() + p[1:] for p in rest)


def base(p):
    """(java type, ts type) for one non-null schema."""
    t = p.get('type')
    if t == 'array':
        j, s = base(p['items'])
        return f'List<{j}>', f'{s}[]'
    if t == 'integer':
        return 'Long', 'number'
    if t == 'boolean':
        return 'Boolean', 'boolean'
    if t == 'object':
        return 'Map<String, Object>', 'Record<string, unknown>'
    if 'enum' in p:
        return 'String', ' | '.join(json.dumps(v) for v in p['enum'])
    fmt = p.get('format')
    if fmt == 'date-time':
        return 'Instant', 'string'
    if fmt == 'date':
        return 'LocalDate', 'string'
    return 'String', 'string'


def field(p):
    if 'anyOf' in p:
        j, s = base(next(x for x in p['anyOf'] if x.get('type') != 'null'))
        return j, f'{s} | null'
    return base(p)


def load():
    aggregates = {e['name']: e['aggregate'] for e in miniyaml.load(str(CATALOGUE))['events']}
    out = []
    for f in sorted(SCHEMAS.glob('*.schema.json')):
        if f.name == 'envelope.schema.json':
            continue
        s = json.loads(f.read_text(encoding='utf-8'))
        name = s['properties']['event_type']['const']
        pay = s['properties']['payload']
        desc = s.get('description', '')
        out.append({'name': name, 'producer': s['properties']['producer']['const'], 'fifo': 'FIFO: True' in desc,
                    'version': s['properties']['schema_version']['const'], 'props': pay['properties'], 'desc': desc,
                    'aggregate': aggregates[name]})
    return out


def java(ev):
    fields = [(k, *field(v)) for k, v in ev['props'].items()]
    imports = sorted({'com.fasterxml.jackson.annotation.JsonProperty'}
                     | ({'java.time.Instant'} if any('Instant' in f[1] for f in fields) else set())
                     | ({'java.time.LocalDate'} if any('LocalDate' in f[1] for f in fields) else set())
                     | ({'java.util.List'} if any('List<' in f[1] for f in fields) else set())
                     | ({'java.util.Map'} if any('Map<' in f[1] for f in fields) else set()))
    params = ',\n'.join(f'        @JsonProperty("{k}") {j} {camel(k)}' for k, j, _ in fields)
    return (f'// {HEADER}\npackage convoy.contracts.events;\n\n'
            + ''.join(f'import {i};\n' for i in imports)
            + f'\n/** {ev["desc"]} */\n'
            f'public record {ev["name"]}(\n{params}) implements EventPayload {{\n'
            f'    public static final String TYPE = "{ev["name"]}";\n'
            f'    public static final String PRODUCER = "{ev["producer"]}";\n'
            f'    public static final String AGGREGATE = "{ev["aggregate"]}";\n'
            f'    public static final boolean FIFO = {str(ev["fifo"]).lower()};\n'
            f'    public static final int SCHEMA_VERSION = {ev["version"]};\n\n'
            f'    @Override public String eventType() {{ return TYPE; }}\n'
            f'}}\n')


def ts(events):
    parts = [f'// {HEADER}\n']
    for ev in events:
        body = ''.join(f'  {k}: {field(v)[1]};\n' for k, v in ev['props'].items())
        parts.append(f'/** {ev["desc"]} */\nexport interface {ev["name"]} {{\n{body}}}\n')
    parts.append('export interface EventPayloads {\n' + ''.join(f'  {e["name"]}: {e["name"]};\n' for e in events) + '}\n')
    parts.append('export type EventType = keyof EventPayloads;\n')
    parts.append('export const EVENT_PRODUCERS: Record<EventType, string> = {\n'
                 + ''.join(f'  {e["name"]}: {json.dumps(e["producer"])},\n' for e in events) + '};\n')
    return '\n'.join(parts)


def files():
    events = load()
    out = {JAVA_DIR / f'{e["name"]}.java': java(e) for e in events}
    out[JAVA_DIR / 'EventPayload.java'] = (f'// {HEADER}\npackage convoy.contracts.events;\n\n'
                                           '/** Marker for generated event payload records. */\n'
                                           'public interface EventPayload {\n    String eventType();\n}\n')
    out[JAVA_DIR / 'EventTypes.java'] = (f'// {HEADER}\npackage convoy.contracts.events;\n\nimport java.util.Map;\n\n'
                                         '/** Event type name -> payload record class. */\npublic final class EventTypes {\n'
                                         '    private EventTypes() {}\n\n'
                                         '    public static final Map<String, Class<? extends EventPayload>> ALL = Map.ofEntries(\n'
                                         + ',\n'.join(f'        Map.entry("{e["name"]}", {e["name"]}.class)' for e in events)
                                         + ');\n}\n')
    subs = miniyaml.load(str(CATALOGUE))['subscriptions']
    out[JAVA_DIR / 'SubscriptionKinds.java'] = (f'// {HEADER}\npackage convoy.contracts.events;\n\nimport java.util.Map;\n\n'
                                                '/** "consumer:aggregate" -> FULL (gap detection), PARTIAL (stale rule only) or EVENTS (dedupe only), from event-catalogue.yaml. */\n'
                                                'public final class SubscriptionKinds {\n    private SubscriptionKinds() {}\n\n'
                                                '    public static final Map<String, String> ALL = Map.ofEntries(\n'
                                                + ',\n'.join(f'        Map.entry("{s["consumer"]}:{s["aggregate"]}", "{s["kind"]}")' for s in subs)
                                                + ');\n}\n')
    out[TS_FILE] = ts(events)
    return out


if __name__ == '__main__':
    stale = []
    want = files()
    if '--check' in sys.argv:
        stale = [str(p.relative_to(ROOT)) for p, t in want.items() if not p.exists() or p.read_text(encoding='utf-8') != t]
        extra = {p for p in JAVA_DIR.glob('*.java')} - set(want)
        stale += [str(p.relative_to(ROOT)) + ' (orphan)' for p in extra]
        if stale:
            sys.exit('stale contracts: ' + ', '.join(stale))
        print('contracts up to date')
    else:
        JAVA_DIR.mkdir(parents=True, exist_ok=True)
        TS_FILE.parent.mkdir(parents=True, exist_ok=True)
        for p in JAVA_DIR.glob('*.java'):
            if p not in want:
                p.unlink()
        for p, t in want.items():
            p.write_text(t, encoding='utf-8', newline='\n')
        print(f'wrote {len(want) - 1} Java files and {TS_FILE.relative_to(ROOT)}')
