"""Generate the catalog service's seed migration from docs/data/catalogue/models.yaml (stdlib only).

python tools/gen_catalog_seed.py          # write services/catalog/src/main/resources/db/migration/V2__seed_catalogue.sql
python tools/gen_catalog_seed.py --check  # exit 1 if stale (CI)

Only VERIFIED variant prices of the P1 models are seeded (P1 rule 4: no invented data). A price is
applied to each plan city; the row is city_confirmed only when the source names that city or all of
India (models.yaml city_rule), otherwise it is shown as "city not confirmed" (Q-003).
"""
import pathlib
import sys
import uuid

ROOT = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / 'spec-tools'))
import miniyaml  # noqa: E402

OUT = ROOT / 'services' / 'catalog' / 'src' / 'main' / 'resources' / 'db' / 'migration' / 'V2__seed_catalogue.sql'
P1_MODELS = ['maruti-swift', 'maruti-dzire', 'maruti-brezza', 'maruti-ertiga', 'hyundai-creta', 'mg-windsor-ev', 'mg-hector']
CITIES = {'Mumbai': 'MH', 'Pune': 'MH', 'Delhi': 'DL', 'Bengaluru': 'KA'}
NS = uuid.UUID('6f1c2d4e-0000-5000-8000-00000000c47a')


def uid(kind, key):
    return str(uuid.uuid5(NS, f'{kind}:{key}'))


def q(v):
    if v is None:
        return 'null'
    if isinstance(v, bool):
        return 'true' if v else 'false'
    if isinstance(v, int):
        return str(v)
    return "'" + str(v).replace("'", "''") + "'"


def sql():
    data = miniyaml.load(ROOT / 'docs' / 'data' / 'catalogue' / 'models.yaml')
    lines = ['-- Generated by tools/gen_catalog_seed.py from docs/data/catalogue/models.yaml. Do not edit.',
             f"-- ruleset {data['ruleset_version']}, collected {data['collected_on']}. VERIFIED variant prices of the P1 models only."]
    brands, found = {}, {}
    for b in data['brands']:
        for m in b['models']:
            if m['id'] in P1_MODELS:
                found[m['id']] = (b['brand'], m)
    missing = [m for m in P1_MODELS if m not in found]
    if missing:
        sys.exit(f'models missing from catalogue: {missing}')
    for mid in P1_MODELS:
        brand, m = found[mid]
        if brand not in brands:
            brands[brand] = uid('brand', brand)
            lines.append(f"insert into brands(id, name) values ({q(brands[brand])}, {q(brand)});")
        src = m['source']
        lines.append(f"insert into models(id, brand_id, slug, name, body_type, source_url, source_title, accessed_on, price_label, city_basis) values "
                     f"({q(uid('model', mid))}, {q(brands[brand])}, {q(mid)}, {q(m['model'])}, {q(m['body'])}, {q(src['url'])}, {q(src['title'])}, "
                     f"{q(src['accessed'])}, {q(src.get('price_label'))}, {q(src.get('city_basis'))});")
        for v in m['variants']:
            if v['status'] != 'VERIFIED' or v['price_paise'] is None:
                continue
            vid = uid('variant', v['id'])
            lines.append(f"insert into variants(id, model_id, code, name, fuel, transmission, engine_cc, note) values "
                         f"({q(vid)}, {q(uid('model', mid))}, {q(v['id'])}, {q(v['name'])}, {q(v.get('fuel'))}, {q(v.get('transmission'))}, "
                         f"{q(v.get('engine_cc'))}, {q(v.get('note'))});")
            for city, state in CITIES.items():
                confirmed = src.get('city_basis') in (city, 'ALL_INDIA')
                lines.append(f"insert into variant_prices(variant_id, city, state_code, ex_showroom_paise, evidence, city_confirmed, source_url, accessed_on) values "
                             f"({q(vid)}, {q(city)}, {q(state)}, {q(v['price_paise'])}, 'CATALOGUE_ESTIMATE', {q(confirmed)}, {q(src['url'])}, {q(src['accessed'])});")
    return '\n'.join(lines) + '\n'


if __name__ == '__main__':
    text = sql()
    if '--check' in sys.argv:
        if not OUT.exists() or OUT.read_text(encoding='utf-8') != text:
            sys.exit('catalogue seed is stale: run tools/gen_catalog_seed.py')
        print('catalogue seed up to date')
    else:
        OUT.parent.mkdir(parents=True, exist_ok=True)
        OUT.write_text(text, encoding='utf-8', newline='\n')
        print(f'wrote {OUT.relative_to(ROOT)} ({text.count("insert into variants")} variants)')
