// Generate the typed API client schema from each service's OpenAPI document (springdoc /v3/api-docs).
//   node scripts/gen-api.mjs            fetch from the running docker compose stack, then generate
//   node scripts/gen-api.mjs --offline  regenerate types from the committed openapi/*.json only
import { execFileSync } from 'node:child_process';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import openapiTS, { astToString } from 'openapi-typescript';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..');
const specDir = join(root, 'lib', 'api', 'openapi');
const outDir = join(root, 'lib', 'api', 'schema');
const SERVICES = ['identity', 'catalog', 'dealer', 'pool', 'quote', 'order', 'payment', 'notification', 'audit'];
mkdirSync(specDir, { recursive: true });
mkdirSync(outDir, { recursive: true });

for (const svc of SERVICES) {
  if (!process.argv.includes('--offline')) {
    const raw = execFileSync('docker', ['compose', 'exec', '-T', svc, 'wget', '-qO-', 'localhost:8080/v3/api-docs'], { cwd: join(root, '..'), encoding: 'utf8' });
    const spec = JSON.parse(raw);
    delete spec.servers; // environment-specific
    writeFileSync(join(specDir, `${svc}.json`), JSON.stringify(spec, null, 2) + '\n');
  }
  const spec = JSON.parse(readFileSync(join(specDir, `${svc}.json`), 'utf8'));
  const ast = await openapiTS(spec);
  writeFileSync(join(outDir, `${svc}.ts`), `// Generated by scripts/gen-api.mjs from lib/api/openapi/${svc}.json. Do not edit.\n` + astToString(ast));
}
writeFileSync(join(outDir, '..', 'schema.ts'),
  '// Generated by scripts/gen-api.mjs. Do not edit.\n'
  + SERVICES.map((s) => `import type { components as ${s}Components, paths as ${s} } from './schema/${s}';`).join('\n')
  + `\n\nexport type paths = ${SERVICES.join(' & ')};\n`
  + `\n/** Response and request records per service, e.g. Schemas['pool']['Pool']. */\nexport interface Schemas {\n`
  + SERVICES.map((s) => `  ${s}: ${s}Components['schemas'];`).join('\n') + '\n}\n');
console.log(`generated API types for ${SERVICES.length} services`);
