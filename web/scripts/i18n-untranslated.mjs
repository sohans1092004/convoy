// Lists user-visible English still hard-coded in the buyer journey (so not translatable yet).
//   node scripts/i18n-untranslated.mjs   -> writes ../reports/p2/i18n-untranslated.md
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const FILES = ['app/page.tsx', 'app/sign-in/page.tsx', 'app/models/[slug]/page.tsx', 'app/saved/page.tsx', 'app/orders/page.tsx', 'app/orders/[id]/page.tsx',
  'app/pools/[id]/compare/page.tsx', 'app/error.tsx', 'components/discover.tsx', 'components/model-estimate.tsx', 'components/pool-view.tsx', 'components/compare-view.tsx',
  'components/order-view.tsx', 'components/my-cars.tsx', 'components/command-status.tsx', 'components/breakdown.tsx'];
const rows = [];
for (const f of FILES) {
  let src;
  try { src = readFileSync(join(process.cwd(), f), 'utf8'); } catch { continue; }
  src.split('\n').forEach((line, i) => {
    if (/^\s*(\/\/|\*|\/\*|import )/.test(line)) return;
    const hits = [
      ...[...line.matchAll(/>([^<>{}]*[A-Za-z]{3,}[^<>{}]*)</g)].map((m) => m[1].trim()),
      ...[...line.matchAll(/(?:label|successText|title|placeholder|aria-label|hint|detail|message)[=:]\s*["'`]([^"'`]*[A-Za-z]{3,}[^"'`]*)["'`]/g)].map((m) => m[1].trim()),
    ].filter((s) => s && !/^[A-Z_]+$/.test(s));
    for (const h of hits) rows.push(`| ${f}:${i + 1} | ${h.replace(/\|/g, '\|').slice(0, 120)} |`);
  });
}
const out = `# Untranslated buyer-journey strings (P2)

Generated by \`node web/scripts/i18n-untranslated.mjs\`. These English strings are hard-coded in components, so the Hindi
locale shows them in English. Everything in \`web/messages/en.json\` (${''}the discover page, join panel, pool page, pre-commit
terms, confirmation copy, closed-pool explanations, navigation) is translated in \`hi.json\` (machine-drafted, needs native
review: see web/messages/README.md).

${rows.length} strings:

| Where | Text |
|---|---|
${rows.join('\n')}
`;
writeFileSync(join(process.cwd(), '..', 'reports', 'p2', 'i18n-untranslated.md'), out);
console.log(`${rows.length} untranslated strings listed`);
